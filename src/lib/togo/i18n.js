/**
 * Resolve the active configurator locale. Precedence:
 *   valid `?lang` query > valid dealer locale (from the togo-embed catalog) > es.
 * Anything not in TOGO_LOCALES is ignored, so a junk `?lang=xx` falls through.
 */
export function resolveTogoLocale({ queryLang, dealerLocale } = {}) {
  if (TOGO_LOCALES.includes(queryLang)) return queryLang;
  if (TOGO_LOCALES.includes(dealerLocale)) return dealerLocale;
  return DEFAULT_TOGO_LOCALE;
}

// `{name}`-style interpolation. A missing var leaves its placeholder intact
// rather than printing "undefined".
function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/**
 * Translate `key` in `locale`, interpolating `vars`. Never throws:
 *   - a locale that misses the key falls back to the `es` source of truth,
 *   - a key no dictionary has returns the key itself (so a typo is visible, not
 *     a crash).
 */
export function t(locale, key, vars) {
  const dict = DICTS[locale] || DICTS[DEFAULT_TOGO_LOCALE];
  let str = dict[key];
  if (str == null) str = DICTS[DEFAULT_TOGO_LOCALE][key]; // fall back to es
  if (str == null) return key; // unknown key → surface the key
  return interpolate(str, vars);
}

/**
 * The localized "{n} piece(s)" label — the shared piece-count phrase used by the
 * estimate deck, the canvas aria-label and the SR narration. Singular for 1,
 * plural otherwise (close enough for the four supported locales).
 */
export function piecesLabel(locale, count) {
  return t(locale, count === 1 ? 'pieces.one' : 'pieces.other', { count });
}

/**
 * The key set of one locale's dictionary — the hook the key-parity fitness test
 * uses to prove every locale carries exactly the same keys (a missing
 * translation would otherwise silently fall back to Spanish for that dealer).
 */
export function localeKeys(locale) {
  return Object.keys(DICTS[locale] || {});
}
